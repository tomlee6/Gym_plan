"""
Rebuilds weights.lock.json: every model file the worker loads, at a fixed
Hugging Face revision, with its size and SHA-256 (task L-11).

TRELLIS.2 fetches weights from four repositories by name, always from
`main`. The worker instead loads them from one local folder laid out as
below, filled by fetch_weights.py from exactly these files (checked against
the hashes here), so the model cannot change under us:

    pipeline.json                         ours (L-12): points every model at this folder
    upstream/pipeline.json                Microsoft's, for comparison
    ckpts/...                             microsoft/TRELLIS.2-4B
    ckpts/ss_dec_conv3d_16l8_fp16.*       microsoft/TRELLIS-image-large (one decoder)
    dinov3/...                            facebook/dinov3-vitl16-pretrain-lvd1689m (gated)
    birefnet/...                          ZhengPeng7/BiRefNet (MIT; in place of RMBG-2.0, L-12)

Large files carry their SHA-256 in the Hub's API; small ones are downloaded
and hashed. DINOv3 is gated: without HF_TOKEN from an account whose access
was approved, its hashes are left empty and fetch_weights.py refuses to use
it until they are filled in.

Run from this folder, with HF_TOKEN set once DINOv3 access is approved:

    python lock_weights.py
"""
from __future__ import annotations

import fnmatch
import hashlib
import json
import os
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent

SOURCES = [
    {
        "repo": "microsoft/TRELLIS.2-4B",
        "revision": "af44b45f2e35a493886929c6d786e563ec68364d",
        "license": "MIT",
        "files": ["ckpts/*"],
        "to": "",
    },
    {
        # Microsoft's own config, kept beside ours (L-12) for comparison.
        "repo": "microsoft/TRELLIS.2-4B",
        "revision": "af44b45f2e35a493886929c6d786e563ec68364d",
        "license": "MIT",
        "files": ["pipeline.json"],
        "to": "upstream/",
    },
    {
        "repo": "microsoft/TRELLIS-image-large",
        "revision": "25e0d31ffbebe4b5a97464dd851910efc3002d96",
        "license": "MIT",
        "files": ["ckpts/ss_dec_conv3d_16l8_fp16.json", "ckpts/ss_dec_conv3d_16l8_fp16.safetensors"],
        "to": "",
    },
    {
        "repo": "facebook/dinov3-vitl16-pretrain-lvd1689m",
        "revision": "ea8dc2863c51be0a264bab82070e3e8836b02d51",
        "license": "DINOv3 License (commercial use allowed; access approved by Meta)",
        "files": ["config.json", "model.safetensors", "preprocessor_config.json", "LICENSE.md"],
        "to": "dinov3/",
        "gated": True,
    },
    {
        "repo": "ZhengPeng7/BiRefNet",
        "revision": "e2bf8e4460fc8fa32bba5ea4d94b3233d367b0e4",
        "license": "MIT",
        "files": ["config.json", "BiRefNet_config.py", "birefnet.py", "model.safetensors"],
        "to": "birefnet/",
    },
]


def get(url: str):
    headers = {"Authorization": f"Bearer {os.environ['HF_TOKEN']}"} if os.environ.get("HF_TOKEN") else {}
    return urllib.request.urlopen(urllib.request.Request(url, headers=headers))


def sha256_of(repo: str, revision: str, path: str) -> str:
    h = hashlib.sha256()
    with get(f"https://huggingface.co/{repo}/resolve/{revision}/{path}") as r:
        for chunk in iter(lambda: r.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> None:
    files = []
    pending = []
    for src in SOURCES:
        with get(f"https://huggingface.co/api/models/{src['repo']}/tree/{src['revision']}?recursive=true") as r:
            tree = [f for f in json.load(r) if f["type"] == "file"]
        chosen = [f for f in tree if any(fnmatch.fnmatch(f["path"], p) for p in src["files"])]
        missing = [p for p in src["files"] if not any(fnmatch.fnmatch(f["path"], p) for f in tree)]
        if missing:
            raise SystemExit(f"{src['repo']}@{src['revision']} has no {missing}")
        for f in sorted(chosen, key=lambda f: f["path"]):
            sha = (f.get("lfs") or {}).get("oid")
            if not sha or "*" in sha:
                try:
                    sha = sha256_of(src["repo"], src["revision"], f["path"])
                except OSError:
                    # A gated file without approved access: no hash yet.
                    sha = None
                    pending.append(f"{src['repo']}/{f['path']}")
            files.append(
                {
                    "path": src["to"] + f["path"],
                    "repo": src["repo"],
                    "revision": src["revision"],
                    "source": f["path"],
                    "size": f["size"],
                    "sha256": sha,
                }
            )
    lock = {
        "comment": "Generated by lock_weights.py. Every file the TRELLIS.2 worker loads, by revision and SHA-256.",
        "sources": [{k: v for k, v in s.items() if k in ("repo", "revision", "license", "gated")} for s in SOURCES],
        "files": files,
        "pending": pending,
    }
    (HERE / "weights.lock.json").write_text(json.dumps(lock, indent=2) + "\n", encoding="utf-8")
    total = sum(f["size"] for f in files)
    print(f"Locked {len(files)} files, {total / 1e9:.1f} GB." + (f" No hash yet (gated): {pending}" if pending else ""))


if __name__ == "__main__":
    main()
